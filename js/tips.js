// 単語の小ネタ。item は単語データ（{ word, tip }）か単語の文字列
export function tipFor(item) {
  if (!item) return null;
  if (typeof item === 'object' && item.tip) return item.tip;
  const word = typeof item === 'string' ? item : item.word;
  return WORD_TIPS[word] || null;
}

// 文化の小ネタをランダムに1つ。直前と同じものは避ける
const LAST_KEY = 'handit_last_culture_tip';
export function randomCultureTip() {
  const n = CULTURE_TIPS.length;
  let last = -1;
  try { last = parseInt(sessionStorage.getItem(LAST_KEY) ?? '-1', 10); } catch {}
  let i = Math.floor(Math.random() * n);
  if (n > 1 && i === last) i = (i + 1) % n;
  try { sessionStorage.setItem(LAST_KEY, String(i)); } catch {}
  return CULTURE_TIPS[i];
}
